//! Minimal UI localisation.
//!
//! The English text in the code is the key: `tr("Cancel")` returns `"취소"` when the UI
//! language is Korean and the key is in the table, otherwise the English key itself. Keys with
//! `{name}` placeholders go through `trf`, which substitutes the arguments after translation.
//! The language is a process-wide setting (one UI, one language), chosen in Settings and
//! stored in the config.
//!
//! A unit test in `app::ui_tests` checks that every `tr("…")` key in the UI sources has a
//! Korean entry, so a missing translation fails CI instead of showing up as mixed-language UI.

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::sync::atomic::{AtomicU8, Ordering};
use std::sync::OnceLock;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Lang {
    #[default]
    Ko,
    En,
}

impl Lang {
    pub fn label(self) -> &'static str {
        match self {
            Lang::Ko => "한국어",
            Lang::En => "English",
        }
    }
}

static LANG: AtomicU8 = AtomicU8::new(0);

pub fn set_lang(l: Lang) {
    LANG.store(l as u8, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    match LANG.load(Ordering::Relaxed) {
        1 => Lang::En,
        _ => Lang::Ko,
    }
}

fn table() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| KO.iter().copied().collect())
}

/// Whether `key` has a Korean entry (used by the translation-completeness test).
#[cfg(test)]
pub fn known(key: &str) -> bool {
    table().contains_key(key)
}

/// The language is process-global; tests that switch it hold this lock so they do not race.
#[cfg(test)]
pub fn test_lock() -> std::sync::MutexGuard<'static, ()> {
    static LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());
    LOCK.lock().unwrap_or_else(|e| e.into_inner())
}

/// Translate a UI string (the English key). Unknown keys and English mode return the key.
pub fn tr(en: &'static str) -> &'static str {
    match lang() {
        Lang::En => en,
        Lang::Ko => table().get(en).copied().unwrap_or(en),
    }
}

/// Translate a string with `{name}` placeholders, then substitute `args`
/// (each `("{name}", value)`).
pub fn trf(en: &'static str, args: &[(&str, &dyn std::fmt::Display)]) -> String {
    let mut s = tr(en).to_string();
    for (k, v) in args {
        s = s.replace(k, &v.to_string());
    }
    s
}

